"""Detection rule research lab.

  python lab.py new <name>              scaffold hypotheses/<name>/ from the templates
  python lab.py generate <name>         run the hypothesis' generate_events.py -> events.jsonl
  python lab.py test <name> [--report]  evaluate rule.yml against events.jsonl
  python lab.py test --all              test every hypothesis

`test` exits non-zero when any event's outcome differs from its "_lab.expect", so it can
gate a CI job. --report also writes results.md next to the rule.
"""

import argparse
import json
import pathlib
import runpy
import shutil
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

from sigma_lite import SigmaRule  # noqa: E402

ROOT = pathlib.Path(__file__).parent
HYPOTHESES = ROOT / "hypotheses"
TEMPLATES = ROOT / "templates"


def hypothesis_dir(name):
    path = HYPOTHESES / name
    if not path.is_dir():
        sys.exit(f"no such hypothesis: {path}")
    return path


def cmd_new(args):
    dest = HYPOTHESES / args.name
    if dest.exists():
        sys.exit(f"{dest} already exists")
    shutil.copytree(TEMPLATES, dest)
    print(f"created {dest}\n  1. write HYPOTHESIS.md\n  2. draft rule.yml\n"
          f"  3. add cases to generate_events.py\n  4. python lab.py generate {args.name}\n"
          f"  5. python lab.py test {args.name} --report")


def cmd_generate(args):
    path = hypothesis_dir(args.name)
    runpy.run_path(str(path / "generate_events.py"), run_name="__lab__")["main"](path / "events.jsonl")


def load_events(path):
    with path.open(encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def run_tests(path):
    rule = SigmaRule.from_file(path / "rule.yml")
    rows = []
    for ev in load_events(path / "events.jsonl"):
        lab = ev.get("_lab", {})
        fields = {k: v for k, v in ev.items() if k != "_lab"}
        got = "match" if rule.matches(fields) else "no_match"
        hits = [n for n, hit in rule.explain(fields).items() if hit]
        rows.append({**lab, "got": got, "ok": got == lab.get("expect"), "hits": hits})
    return rule, rows


def print_table(rule, rows):
    print(f"\nRule: {rule.title}")
    print(f"Condition: {rule.condition_text}\n")
    for r in rows:
        mark = "PASS" if r["ok"] else "FAIL"
        print(f"  [{mark}] {r['id']:<6} {r['category']:<21} expect={r['expect']:<8} got={r['got']:<8} {r['why']}")
        if not r["ok"]:
            print(f"         searches that matched: {', '.join(r['hits']) or '(none)'}")
    passed = sum(r["ok"] for r in rows)
    print(f"\n{passed}/{len(rows)} cases behave as expected")
    for cat in ("true_positive", "true_negative", "known_false_positive", "known_false_negative"):
        n = sum(r["category"] == cat for r in rows)
        if n:
            print(f"  {cat:<21} {n}")


def write_report(path, rule, rows):
    lines = [
        f"# Test results: {rule.title}", "",
        "Generated by `python lab.py test <name> --report`. Do not edit by hand.", "",
        f"**{sum(r['ok'] for r in rows)}/{len(rows)}** cases behave as expected.", "",
        "| ID | Category | Expected | Got | Result | Matched searches | Case |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['id']} | {r['category']} | {r['expect']} | {r['got']} | {'PASS' if r['ok'] else '**FAIL**'} "
            f"| {', '.join(f'`{h}`' for h in r['hits']) or '-'} | {r['why']} |"
        )
    (path / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {path / 'results.md'}")


def cmd_test(args):
    names = sorted(p.name for p in HYPOTHESES.iterdir() if p.is_dir()) if args.all else [args.name]
    if not names or names == [None]:
        sys.exit("give a hypothesis name or --all")
    failed = False
    for name in names:
        path = hypothesis_dir(name)
        if not (path / "events.jsonl").exists():
            cmd_generate(argparse.Namespace(name=name))
        rule, rows = run_tests(path)
        print_table(rule, rows)
        if args.report:
            write_report(path, rule, rows)
        failed |= not all(r["ok"] for r in rows)
    sys.exit(1 if failed else 0)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("new")
    p.add_argument("name")
    p.set_defaults(func=cmd_new)
    p = sub.add_parser("generate")
    p.add_argument("name")
    p.set_defaults(func=cmd_generate)
    p = sub.add_parser("test")
    p.add_argument("name", nargs="?")
    p.add_argument("--all", action="store_true")
    p.add_argument("--report", action="store_true")
    p.set_defaults(func=cmd_test)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
